import { readFile, writeFile, mkdir } from "node:fs/promises";
import { evaluateHouse, ENGINE_VERSION } from "../src/house-engine.js";
import { generateHouse } from "../src/house-generator.js";
import { exportPlanSVG } from "../src/house-exports.js";
let storedReport;
try {
  storedReport = JSON.parse(await readFile(new URL("../public/engine-report.json", import.meta.url), "utf8"));
} catch {}
if (storedReport?.engine?.projectId?.startsWith("house-") && storedReport?.engine?.revision > 0) {
  await writeFile(new URL("../public/engine-plan.svg", import.meta.url), exportPlanSVG(storedReport));
  process.stdout.write(
    `KARKAS ENGINE: preserve MCP project ${storedReport.engine.projectId} revision ${storedReport.engine.revision}\n`,
  );
  process.exit(0);
}
const generated = generateHouse({
  name: "MCP · дом с вторым светом",
  width: 8,
  depth: 4,
  levels: [{ height: 2.8 }, { height: 2.6 }],
  secondLight: {
    level: 2,
    polygon: [
      { x: 0.5, y: 0.5 },
      { x: 2.5, y: 0.5 },
      { x: 2.5, y: 2.5 },
      { x: 0.5, y: 2.5 },
    ],
  },
  roof: { shape: "mono", pitch: 18, ridgeAngle: 0, framing: "auto" },
  sections: {
    walls: "50x150",
    floor: "50x200",
    roof: "50x200",
    roofWeb: "50x100",
    grillage: "50x200",
    bracing: "25x100",
  },
  bracing: { method: "letIn" },
  foundation: { spacing: 2, capacity: 40, grillage: { plies: 3, capSize: 250 } },
});
const report = evaluateHouse(generated.project, generated.planning);
report.engine = {
  ...report.engine,
  projectId: "example-house",
  revision: 1,
  source: "Generated by deterministic MCP engine; read-only publication example",
};
await mkdir(new URL("../public/", import.meta.url), { recursive: true });
await writeFile(new URL("../public/engine-report.json", import.meta.url), JSON.stringify(report));
await writeFile(new URL("../public/engine-plan.svg", import.meta.url), exportPlanSVG(report));
process.stdout.write(
  `KARKAS ENGINE ${ENGINE_VERSION}: example ${report.summary.boards} pieces, ${report.summary.stockBoards} stocks, ${report.summary.piles} piles\n`,
);
